import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';

// No default paths: a silently wrong distDir would embed the wrong panel.
const [DIST, OUT] = process.argv.slice(2);
if (!DIST || !OUT) {
  console.error('usage: node gen_webui_blob.mjs <distDir> <out.cc>');
  process.exit(1);
}

const MIME = {
  html: 'text/html; charset=utf-8',
  htm: 'text/html; charset=utf-8',
  js: 'text/javascript; charset=utf-8',
  mjs: 'text/javascript; charset=utf-8',
  css: 'text/css; charset=utf-8',
  json: 'application/json',
  map: 'application/json',
  svg: 'image/svg+xml',
  png: 'image/png',
  jpg: 'image/jpeg',
  jpeg: 'image/jpeg',
  gif: 'image/gif',
  webp: 'image/webp',
  ico: 'image/x-icon',
  txt: 'text/plain; charset=utf-8',
  wasm: 'application/wasm',
  woff: 'font/woff',
  woff2: 'font/woff2',
  ttf: 'font/ttf',
};
const mimeFor = (p) =>
  MIME[p.split('.').pop().toLowerCase()] || 'application/octet-stream';

function walk(dir, base = '') {
  let out = [];
  for (const name of fs.readdirSync(dir)) {
    const full = path.join(dir, name);
    const rel = base ? base + '/' + name : name;
    if (fs.statSync(full).isDirectory()) out = out.concat(walk(full, rel));
    else out.push({ rel, full });
  }
  return out;
}

const u32 = (v) => {
  const b = Buffer.allocUnsafe(4);
  b.writeUInt32LE(v >>> 0, 0);
  return b;
};

const files = walk(DIST).sort((a, b) => a.rel.localeCompare(b.rel));
const chunks = [Buffer.from('AWEB', 'ascii'), u32(1), u32(files.length)];
for (const f of files) {
  const data = fs.readFileSync(f.full);
  const p = Buffer.from(f.rel, 'utf8');
  const m = Buffer.from(mimeFor(f.rel), 'utf8');
  chunks.push(u32(p.length), p, u32(m.length), m, u32(data.length), data);
}
const raw = Buffer.concat(chunks);
const comp = zlib.deflateSync(raw, { level: 9 });
const b64 = Buffer.concat([u32(raw.length), comp]).toString('base64');

const LINE = 120;
let lit = '';
for (let i = 0; i < b64.length; i += LINE) {
  lit += '"' + b64.slice(i, i + LINE) + '"\n';
}
const src =
  '// Generated by scripts/gen_webui_blob.mjs. DO NOT EDIT.\n' +
  '// Embedded Web UI archive: base64(zlib(deflate(AWEB index))).\n' +
  'namespace aria2 {\n\n' +
  'extern const char WEBUI_BLOB_B64[] =\n' +
  lit +
  ';\n\n' +
  'extern const unsigned int WEBUI_BLOB_B64_LEN = ' + b64.length + ';\n\n' +
  '} // namespace aria2\n';

fs.writeFileSync(OUT, src);
console.log(
  `assets=${files.length} raw=${raw.length} deflated=${comp.length} b64=${b64.length} srcBytes=${src.length}`
);
